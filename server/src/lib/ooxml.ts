export type OfficeTemplate = "docx" | "xlsx" | "pptx";

export function buildOfficeTemplate(template: OfficeTemplate): Buffer {
  switch (template) {
    case "docx":
      return buildDocx();
    case "xlsx":
      return buildXlsx();
    case "pptx":
      return buildPptx();
    default:
      throw new Error(`unknown template: ${String(template)}`);
  }
}
